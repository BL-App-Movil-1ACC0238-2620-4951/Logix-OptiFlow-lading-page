const root = document.documentElement,
  store = (k, v) => {
    try {
      return v ? localStorage.setItem(k, v) : localStorage.getItem(k);
    } catch {
      return null;
    }
  };

const orig = new WeakMap();
let lang = store("of-lang") || ((navigator.language || "es").startsWith("en") ? "en" : "es");

window.T = s => (lang === "en" && EN[s] ? EN[s] : s);

function walk() {
  const w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let n;
  while ((n = w.nextNode())) {
    if (n.parentElement.closest("script,style")) continue;
    const t = n.nodeValue.trim();
    if (!orig.has(n)) {
      if (!EN[t]) continue;
      orig.set(n, [n.nodeValue, t]);
    }
    const [o, es] = orig.get(n);
    n.nodeValue = lang === "en" ? o.replace(es, EN[es]) : o;
  }
}

function setLang(l) {
  lang = l;
  store("of-lang", l);
  root.lang = l;
  walk();
  document.title = l === "en" 
    ? "OptiFlow — Your ideal eye appointment, in your pocket" 
    : "OptiFlow — Tu cita óptica ideal, en tu bolsillo";
  const b = document.querySelector("#lang");
  if (b) b.querySelector("span").textContent = l === "en" ? "ES" : "EN";
  b?.setAttribute("aria-label", l === "en" ? "Cambiar a español" : "Switch to English");
}

function setTheme(t) {
  root.dataset.theme = t;
  store("of-theme", t);
  document.querySelector("#theme")?.setAttribute("aria-pressed", t === "dark");
}

setTheme(store("of-theme") || (matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light"));

document.querySelector("#theme").onclick = () => setTheme(root.dataset.theme === "dark" ? "light" : "dark");
document.querySelector("#lang").onclick = () => setLang(lang === "en" ? "es" : "en");

setLang(lang);

